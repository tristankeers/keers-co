"""Record what calculation version kci-v3 changes, against kci-v2, on KCI's 100-company test baseline.

Writes ``tests/golden/kci_v3.json`` (locked by a test) and ``docs/calc/kci-v3-changes.md``. KCI's dataset is used
here only as a fixed baseline for comparing versions, never as input to a live valuation.

The baseline has no betas, so neither v2 nor v3 runs its DCF on it. To show what the debt weight alone does, the
report runs v3's DCF inputs with v1's house beta (1.1), size premium (2%) and risk-free rate (4.5%) put back, once
with the fixed 30% debt weight and once with each company's own. That run is labelled as a comparison and is not
a kci-v3 result.

Usage: python scripts/kci_v3_changes.py [--check]
"""

from __future__ import annotations

import json
import statistics
import sys
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from keers.valuation import kci_v2_defaults as V2  # noqa: E402
from keers.valuation import kci_v3_defaults as V3  # noqa: E402
from scripts.kci_v2_changes import V1_WACC, dcf_ev, mult, pct  # noqa: E402

SEED = ROOT / "legacy" / "kci" / "seed.json"
GOLDEN = ROOT / "tests" / "golden" / "kci_v3.json"
REPORT = ROOT / "docs" / "calc" / "kci-v3-changes.md"


def deals() -> list[dict[str, Any]]:
    return sorted(json.loads(SEED.read_text())["deals"].values(), key=lambda d: d["id"])


def golden() -> list[dict[str, Any]]:
    return V3.summarise(deals())


def _base(a: dict[str, Any]) -> dict[str, Any]:
    r: dict[str, Any] = a["scenarios"]["base"]["result"]
    return r


def report(v3: list[dict[str, Any]]) -> str:
    ds = deals()
    by_id = {d["id"]: d for d in ds}
    v2 = {r["id"]: r for r in V2.summarise(ds)}
    new = [c for c in V3.CHANGES if c not in V2.CHANGES]
    c2 = Counter(v2[r["id"]]["decision"] for r in v3)
    c3 = Counter(r["decision"] for r in v3)
    lines = [
        "# kci-v3: output changes against kci-v2",
        "",
        "Generated by `scripts/kci_v3_changes.py` from KCI's 100-company dataset, which is used only as a fixed",
        "test baseline. kci-v3 keeps every kci-v2 change and adds the items below, which close the rest of the",
        "22 Oct 2026 audit. Companies with a custom model saved in KCI (Dropbox) keep it, so the buyout tax cap and",
        "the verdict rules do not apply to them.",
        "",
        "## What changed",
        "",
        *[f"- {c}" for c in new],
        "",
        "## IC verdicts",
        "",
        "| Verdict | kci-v2 | kci-v3 |",
        "|---|---:|---:|",
        *[f"| {k} | {c2.get(k, 0)} | {c3.get(k, 0)} |" for k in ("Proceed", "Further Research", "Pass")],
        "",
        "Companies whose verdict changed:",
        "",
        "| Company | kci-v2 | kci-v3 | Why |",
        "|---|---|---|---|",
    ]
    for r in v3:
        a = v2[r["id"]]
        if a["decision"] != r["decision"]:
            why = "; ".join(V3.analyse(by_id[r["id"]])["rec"].get("rulesApplied", [])) or "model outputs"
            lines.append(f"| {r['ticker']} | {a['decision']} | {r['decision']} | {why} |")
    lines.append("")

    # Interest cap.
    rows = []
    for r in v3:
        a = v2[r["id"]]
        if r["customModel"] or r["baseIrr"] is None or a["baseIrr"] is None:
            continue
        tax2 = sum(y["tax"] for y in _base(V2.analyse(by_id[r["id"]]))["years"])
        rows.append(
            (r["ticker"], a["baseIrr"], r["baseIrr"], tax2, r["taxPaid"], r["interestCarriedForward"])
        )
    bound = [x for x in rows if x[4] - x[3] > 1e-6]
    lines += [
        "## Interest deduction cap",
        "",
        f"The base-case buyout ran for {len(rows)} companies on default assumptions. The cap binds (more tax is",
        f"paid over the hold) for {len(bound)} of them. Median change in base IRR across all "
        f"{len(rows)}: {abs(statistics.median([x[2] - x[1] for x in rows])) * 100:.2f} percentage points.",
        "",
        "Largest effects:",
        "",
        "| Company | Base IRR v2 → v3 | Tax over the hold, v2 → v3 (USDm) | Interest still carried forward at exit |",
        "|---|---|---|---:|",
        *[
            f"| {t} | {pct(i2)} → {pct(i3)} | {t2:,.0f} → {t3:,.0f} | {cf:,.0f} |"
            for t, i2, i3, t2, t3, cf in sorted(bound, key=lambda x: x[2] - x[1])[:10]
        ],
        "",
    ]

    # Debt weight.
    weights = [r["debtWeight"] for r in v3 if r["debtWeight"] is not None]
    fixed, own, withheld = [], [], 0
    for d in ds:
        if d.get("dcf"):
            continue
        ev = d.get("ev")
        dw = V3.debt_weight(d)
        if not (isinstance(ev, (int, float)) and ev > 0) or dw is None:
            continue
        base = {**V3.default_dcf(d), **V1_WACC}
        e_fixed, e_own = dcf_ev({**base, "debtWeight": 0.3}), dcf_ev(base)
        if e_fixed is None or e_own is None:
            continue
        fixed.append(e_fixed / ev)
        own.append(e_own / ev)
        withheld += e_own <= 0
    lines += [
        "## DCF debt weight",
        "",
        f"Debt weights from the baseline's market data ({len(weights)} companies with gross debt and market",
        f"equity): median {statistics.median(weights):.0%}, lowest {min(weights):.0%}, highest {max(weights):.0%},",
        "against the fixed 30% in kci-v1 and kci-v2.",
        "",
        "With v1's beta, size premium and risk-free rate put back so that only the debt weight differs:",
        "",
        "| | fixed 30% | company's own |",
        "|---|---:|---:|",
        f"| Companies compared | {len(fixed)} | {len(own)} |",
        f"| Median DCF EV / market EV | {statistics.median(fixed):.0%} | {statistics.median(own):.0%} |",
        f"| Zero or negative DCF EV (value per share withheld in v3) | {sum(x <= 0 for x in fixed)} | {withheld} |",
        "",
        "## Buyout eligibility",
        "",
        "Companies where a default buyout is not meaningful:",
        "",
        "| Company | Why | Entry multiple (v3) |",
        "|---|---|---|",
    ]
    for r in v3:
        if not r["eligible"]:
            reasons = "; ".join(V3.eligibility(by_id[r["id"]])["reasons"])
            lines.append(f"| {r['ticker']} | {reasons} | {mult(r['entryMultiple'])} |")
    lines += [
        "",
        "The DCF result with each company's own beta comes from the live data layer, not this baseline.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    v3 = golden()
    text = json.dumps(v3, indent=1, sort_keys=True) + "\n"
    rep = report(v3)
    if "--check" in sys.argv:
        ok = GOLDEN.read_text() == text and REPORT.read_text() == rep
        print("up to date" if ok else "out of date: run python scripts/kci_v3_changes.py")
        return 0 if ok else 1
    GOLDEN.write_text(text)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(rep)
    print(f"wrote {GOLDEN.relative_to(ROOT)} and {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
