"""Record what calculation version kci-v2 changes, against kci-v1, on KCI's 100-company test baseline.

Writes ``tests/golden/kci_v2.json`` (locked by a test) and ``docs/calc/kci-v2-changes.md``. KCI's dataset is used
here only as a fixed baseline for comparing versions, never as input to a live valuation.

The baseline has no betas, so kci-v2 refuses to run its DCF on it. To show what the capex fade alone does, the
report also runs both versions' DCF with v1's house beta (1.1), size premium (2%) and risk-free rate (4.5%) put
back. That run is labelled as a comparison and is not a kci-v2 result.

Usage: python scripts/kci_v2_changes.py [--check]
"""

from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path
from typing import Any

from keers.valuation import kci_v1 as K
from keers.valuation import kci_v1_defaults as V1
from keers.valuation import kci_v2_defaults as V2

ROOT = Path(__file__).resolve().parents[1]
SEED = ROOT / "legacy" / "kci" / "seed.json"
GOLDEN = ROOT / "tests" / "golden" / "kci_v2.json"
REPORT = ROOT / "docs" / "calc" / "kci-v2-changes.md"
V1_WACC = {"beta": 1.1, "sizePremium": 0.02, "riskFree": 0.045}


def deals() -> list[dict[str, Any]]:
    return sorted(json.loads(SEED.read_text())["deals"].values(), key=lambda d: d["id"])


def golden() -> list[dict[str, Any]]:
    return V2.summarise(deals())


def dcf_ev(dcf_in: dict[str, Any]) -> float | None:
    dcf_in = V1.fit_dcf(dcf_in)
    w = V1.dcf_wacc(dcf_in)
    if not w["ok"]:
        return None
    r = K.run_dcf({**dcf_in, "wacc": w["value"]})
    return r["primary"]["ev"] if r["ok"] else None


def pct(x: float | None) -> str:
    return "—" if x is None else f"{x:.1%}"


def mult(x: float | None) -> str:
    return "—" if x is None else f"{x:.2f}x"


def report(v2: list[dict[str, Any]]) -> str:
    ds = deals()
    v1 = {r["id"]: r for r in V1.summarise(ds)}
    by_id = {d["id"]: d for d in ds}
    lines = [
        "# kci-v2: output changes against kci-v1",
        "",
        "Generated by `scripts/kci_v2_changes.py` from KCI's 100-company dataset, which is used only as a fixed",
        "test baseline. The engine formulas are unchanged; only the default assumptions differ. Companies with a",
        "custom model saved in KCI (Dropbox) keep it in both versions.",
        "",
        "## What changed",
        "",
        *[f"- {c}" for c in V2.CHANGES],
        "",
    ]
    from collections import Counter

    c1 = Counter(v1[r["id"]]["decision"] for r in v2)
    c2 = Counter(r["decision"] for r in v2)
    lines += [
        "## IC verdicts",
        "",
        "| Verdict | kci-v1 | kci-v2 |",
        "|---|---:|---:|",
        *[f"| {k} | {c1.get(k, 0)} | {c2.get(k, 0)} |" for k in ("Proceed", "Further Research", "Pass")],
        "",
        "Companies whose verdict changed:",
        "",
        "| Company | kci-v1 | kci-v2 | Entry multiple v1 → v2 | Base IRR v1 → v2 |",
        "|---|---|---|---|---|",
    ]
    for r in v2:
        a = v1[r["id"]]
        if a["decision"] != r["decision"]:
            v1_irr = a["base"].get("irr")
            v1_entry = V1.analyse(by_id[r["id"]])["lbo"]
            lines.append(
                f"| {r['ticker']} | {a['decision']} | {r['decision']} | "
                f"{mult(v1_entry['entry']['entryMultiple'] if v1_entry['ok'] else None)} → {mult(r['entryMultiple'])} | "
                f"{pct(v1_irr)} → {pct(r['baseIrr'])} |"
            )
    lines += [""]

    ratio1, ratio2, rows = [], [], []
    for d in ds:
        if d.get("dcf"):
            continue
        ev = d.get("ev")
        e1 = dcf_ev(V1.default_dcf(d))
        e2 = dcf_ev({**V2.default_dcf(d), **V1_WACC})
        if not (isinstance(ev, (int, float)) and ev > 0 and e1 is not None and e2 is not None):
            continue
        ratio1.append(e1 / ev)
        ratio2.append(e2 / ev)
        rows.append((d["ticker"], e1 / ev, e2 / ev))
    neg1 = sum(1 for x in ratio1 if x < 0)
    neg2 = sum(1 for x in ratio2 if x < 0)
    lines += [
        "## DCF: the capex fade alone",
        "",
        "kci-v2 does not run the DCF on this baseline because it has no betas. With v1's beta, size premium and",
        "risk-free rate put back, so that only the capex fade differs:",
        "",
        "| | kci-v1 | capex fade |",
        "|---|---:|---:|",
        f"| Companies compared | {len(ratio1)} | {len(ratio2)} |",
        f"| Median DCF EV / market EV | {statistics.median(ratio1):.0%} | {statistics.median(ratio2):.0%} |",
        f"| Negative DCF EV | {neg1} | {neg2} |",
        "",
        "Largest moves:",
        "",
        "| Company | kci-v1 DCF / market | capex fade DCF / market |",
        "|---|---:|---:|",
        *[
            f"| {t} | {a:.0%} | {b:.0%} |"
            for t, a, b in sorted(rows, key=lambda x: abs(x[2] - x[1]), reverse=True)[:10]
        ],
        "",
        "The DCF result with each company's own beta comes from the live data layer, not this baseline.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    v2 = golden()
    text = json.dumps(v2, indent=1, sort_keys=True) + "\n"
    rep = report(v2)
    if "--check" in sys.argv:
        ok = GOLDEN.read_text() == text and REPORT.read_text() == rep
        print("up to date" if ok else "out of date: run python scripts/kci_v2_changes.py")
        return 0 if ok else 1
    GOLDEN.write_text(text)
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(rep)
    print(f"wrote {GOLDEN.relative_to(ROOT)} and {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
